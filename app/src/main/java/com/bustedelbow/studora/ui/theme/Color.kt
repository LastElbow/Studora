// ---------------------------------------------------------------------------
// Heat ramp — the one deliberate non-MD3 semantic exception.
//
// Fixed GitHub-contribution greens, independent of the seed/wallpaper, so the
// "darker means more focus" contract survives any theming. Light ramp darkens
// as intensity rises; dark ramp brightens as intensity rises (inverted so the
// busiest days stay the most salient on a dark surface).
//
// Order: none, light, medium, dark, intense.
// ---------------------------------------------------------------------------

private val HeatNoneLight: Color = Color(0xFFEBEDF0)
private val HeatLightLight: Color = Color(0xFF9BE9A8)
private val HeatMediumLight: Color = Color(0xFF40C463)
private val HeatDarkLight: Color = Color(0xFF30A14E)
private val HeatIntenseLight: Color = Color(0xFF216E39)

private val HeatNoneDark: Color = Color(0xFF161B22)
private val HeatLightDark: Color = Color(0xFF0E4429)
private val HeatMediumDark: Color = Color(0xFF006D32)
private val HeatDarkDark: Color = Color(0xFF26A641)
private val HeatIntenseDark: Color = Color(0xFF39D353)

/** Heat ramp slot 0/4 — no completed sessions. Theme-aware. */
val HeatNone: Color
    @Composable
    get() = if (isSystemInDarkTheme()) HeatNoneDark else HeatNoneLight

/** Heat ramp slot 1/4 — 1 completed session. Theme-aware. */
val HeatLight: Color
    @Composable
    get() = if (isSystemInDarkTheme()) HeatLightDark else HeatLightLight

/** Heat ramp slot 2/4 — 2-3 completed sessions. Theme-aware. */
val HeatMedium: Color
    @Composable
    get() = if (isSystemInDarkTheme()) HeatMediumDark else HeatMediumLight

/** Heat ramp slot 3/4 — 4-5 completed sessions. Theme-aware. */
val HeatDark: Color
    @Composable
    get() = if (isSystemInDarkTheme()) HeatDarkDark else HeatDarkLight

/** Heat ramp slot 4/4 — 6+ completed sessions. Theme-aware. */
val HeatIntense: Color
    @Composable
    get() = if (isSystemInDarkTheme()) HeatIntenseDark else HeatIntenseLight

/**
 * The full heat ramp for the current theme, ordered none -> intense, ready to
 * index by shade level (0..4).
 */
@Composable
fun heatmapRamp(): List<Color> = listOf(HeatNone, HeatLight, HeatMedium, HeatDark, HeatIntense)
